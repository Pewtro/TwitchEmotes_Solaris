local ROOT = "Interface\\AddOns\\TwitchEmotes_Solaris\\Emotes\\"

TwitchEmotes_Solaris_Emoticons = {}
TwitchEmotes_Solaris_Emoticons_Pack = {}
TwitchEmotes_Solaris_Animation_Metadata = {}

local function addEmote(name, folder, width, height)
    TwitchEmotes_Solaris_Emoticons[name] = name
    TwitchEmotes_Solaris_Emoticons_Pack[name] = ROOT .. folder .. name .. ".tga:" .. width .. ":" .. height
end

local function addAnimation(name, frames, imageHeight, framerate, wide)
    local folder = wide and "animated\\wide\\" or "animated\\"
    local frameWidth = wide and 128 or 32
    local path = ROOT .. folder .. name .. ".tga"
    TwitchEmotes_Solaris_Animation_Metadata[path] = {
        nFrames = frames, frameWidth = frameWidth, frameHeight = 32,
        imageWidth = frameWidth, imageHeight = imageHeight, framerate = framerate,
    }
end

